class SafeLdapAuditor:
    """Read-only LDAP/LDAPS client with adaptive timeouts, retries, and paged search."""


    def __init__(
        self,
        dc_ip: str,
        domain: str,
        username: str,
        password: str,
        base_dn: Optional[str] = None,
        ldap_port: Optional[int] = None,
        use_ssl: bool = False,
        insecure_tls: bool = False,
        attempts: int = 3,
        base_timeout: float = 6.0,
        page_size: int = 500,
    ) -> None:
        """Initialize LDAP connection parameters."""
        self.dc_ip = dc_ip
        self.domain = domain
        self.username = username
        self.password = password
        self.base_dn = base_dn or domain_to_base_dn(domain)
        self.use_ssl = use_ssl
        self.insecure_tls = insecure_tls
        self.attempts = max(1, attempts)
        self.base_timeout = max(1.0, base_timeout)
        self.page_size = max(50, page_size)


        self.port = int(ldap_port) if ldap_port else (636 if use_ssl else 389)
        self.user = f"{domain}\\{username}" if domain else username
        self.authentication = ldap3.NTLM if domain else ldap3.SIMPLE


    def _create_tls_config(self) -> Optional[ldap3.Tls]:
        """Create TLS configuration for LDAPS connections."""
        if not self.use_ssl:
            return None


        validate = ssl.CERT_NONE if self.insecure_tls else ssl.CERT_REQUIRED
        return ldap3.Tls(validate=validate)


    def _connect(self, timeout: float) -> ldap3.Connection:
        """Create and bind an LDAP connection with the specified timeout."""
        tls_config = self._create_tls_config()


        server = ldap3.Server(
            host=self.dc_ip,
            port=self.port,
            use_ssl=self.use_ssl,
            tls=tls_config,
            get_info=ldap3.ALL,
            connect_timeout=timeout,
            read_timeout=timeout,
        )


        connection = ldap3.Connection(
            server,
            user=self.user,
            password=self.password,
            authentication=self.authentication,
            auto_bind=False,
            client_strategy=ldap3.SYNC,
            receive_timeout=timeout,
            raise_exceptions=False,
        )


        if not connection.bind():
            raise RuntimeError(f"LDAP bind failed: {connection.result}")


        return connection


    def _paged_search(
        self,
        connection: ldap3.Connection,
        search_filter: str,
        attributes: Sequence[str],
    ) -> Generator[Dict[str, Any], None, None]:
        """Perform paged LDAP subtree search and normalize entry attributes."""
        entries = connection.extend.standard.paged_search(
            search_base=self.base_dn,
            search_filter=search_filter,
            search_scope=ldap3.SUBTREE,
            attributes=list(attributes),
            paged_size=self.page_size,
            iterator=True,
        )


        for entry in entries:
            if entry.get("type") != "searchResEntry":
                continue


            raw_attributes = entry.get("attributes", {})
            normalized = {}


            for key, value in raw_attributes.items():
                if isinstance(value, (list, tuple, set)):
                    normalized[key] = [str(item) for item in value]
                elif value is None:
                    normalized[key] = None
                else:
                    normalized[key] = str(value)


            yield {
                "dn": str(entry.get("dn", "")),
                "attributes": normalized,
            }


    def search(
        self,
        check_name: str,
        search_filter: str,
        attributes: Sequence[str],
    ) -> List[Dict[str, Any]]:
        """Execute resilient LDAP search with automatic retries on transient network errors."""
        last_error: Optional[Exception] = None


        for attempt in range(self.attempts):
            connection: Optional[ldap3.Connection] = None
            timeout = adaptive_timeout(self.base_timeout, attempt)


            try:
                connection = self._connect(timeout)
                return list(self._paged_search(connection, search_filter, attributes))


            except RuntimeError:
                raise


            except (
                socket.timeout,
                socket.error,
                TimeoutError,
                LDAPCommunicationError,
                LDAPSocketOpenError,
                LDAPSocketReceiveError,
                LDAPException,
            ) as exc:
                last_error = exc


                if attempt + 1 < self.attempts:
                    delay = backoff_delay(self.base_timeout, attempt)
                    time.sleep(delay)


            finally:
                if connection is not None:
                    try:
                        connection.unbind()
                    except Exception:
                        pass


        raise RuntimeError(
            f"LDAP search '{check_name}' failed after {self.attempts} attempts: "
            f"{last_error}"
        )




