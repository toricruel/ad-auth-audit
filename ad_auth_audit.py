def render_output(store: ResultStore, args: argparse.Namespace) -> None:
    """Render audit findings, noisy events, and errors to the console."""
    snapshot = store.snapshot()


    if RICH_AVAILABLE:
        console = Console()


        console.print(f"[bold cyan]Run ID:[/bold cyan] {RUN_ID}")
        console.print(f"[bold cyan]Domain:[/bold cyan] {args.domain}")
        console.print(f"[bold cyan]DC:[/bold cyan] {args.dc_ip}")
        console.print("")


        findings_table = Table(title="AD Authentication Configuration Findings")
        findings_table.add_column("Time", overflow="fold")
        findings_table.add_column("Check", overflow="fold")
        findings_table.add_column("Severity", overflow="fold")
        findings_table.add_column("Object", overflow="fold")
        findings_table.add_column("Summary", overflow="fold")


        for finding in snapshot["findings"]:
            findings_table.add_row(
                finding["timestamp"],
                finding["check_id"],
                finding["severity"],
                finding["object_name"],
                finding["summary"],
            )


        if snapshot["findings"]:
            console.print(findings_table)
        else:
            console.print("[green]No risky account configurations found.[/green]")


        if snapshot["events"]:
            events_table = Table(title="Controlled Noisy Network Events")
            events_table.add_column("Time", overflow="fold")
            events_table.add_column("Destination", overflow="fold")
            events_table.add_column("Port", justify="right")
            events_table.add_column("Status", overflow="fold")
            events_table.add_column("Attempt", justify="right")
            events_table.add_column("Timeout", justify="right")


            for event in snapshot["events"]:
                events_table.add_row(
                    event["timestamp"],
                    event["destination"],
                    str(event["port"]),
                    event["status"],
                    str(event["attempt"]),
                    str(event["timeout"]),
                )


            console.print(events_table)


        if snapshot["errors"]:
            errors_table = Table(title="Errors")
            errors_table.add_column("Time", overflow="fold")
            errors_table.add_column("Stage", overflow="fold")
            errors_table.add_column("Message", overflow="fold")


            for error in snapshot["errors"]:
                errors_table.add_row(
                    error["timestamp"],
                    error["stage"],
                    error["message"],
                )


            console.print(errors_table)


    else:
        print(f"Run ID: {RUN_ID}")
        print(f"Domain: {args.domain}")
        print(f"DC: {args.dc_ip}")
        print()


        print("== Findings ==")
        if snapshot["findings"]:
            for finding in snapshot["findings"]:
                print(json.dumps(finding, ensure_ascii=False))
        else:
            print("No risky account configurations found.")


        if snapshot["events"]:
            print("\n== Noisy events ==")
            for event in snapshot["events"]:
                print(json.dumps(event, ensure_ascii=False))


        if snapshot["errors"]:
            print("\n== Errors ==")
            for error in snapshot["errors"]:
                print(json.dumps(error, ensure_ascii=False))




def write_json(store: ResultStore, args: argparse.Namespace) -> None:
    """Export audit results and metrics to JSON for ELK/SIEM ingestion."""
    snapshot = store.snapshot()


    payload = {
        "run_id": RUN_ID,
        "generated_at": utc_now_iso(),
        "tool": "ad_auth_audit",
        "mode": "defensive-audit",
        "domain": args.domain,
        "dc_ip": args.dc_ip,
        "ldap_base_dn": args.base_dn or domain_to_base_dn(args.domain),
        "ldap_port": args.ldap_port or (636 if args.use_ssl else 389),
        "use_ssl": args.use_ssl,
        "noisy_enabled": args.noisy,
        "findings": snapshot["findings"],
        "noisy_events": snapshot["events"],
        "errors": snapshot["errors"],
        "metrics": snapshot["metrics"],
    }


    if args.json == "-":
        json.dump(payload, sys.stdout, ensure_ascii=False, indent=2)
        sys.stdout.write("\n")
    else:
        with open(args.json, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, ensure_ascii=False, indent=2)
            handle.write("\n")




