def _tcp_probe(target: str, port: int, timeout: float) -> Tuple[str, str]:
    """Perform a single TCP handshake probe without sending any payload."""
    try:
        with socket.create_connection((target, port), timeout=timeout):
            return "connected", ""


    except (socket.timeout, TimeoutError) as exc:
        return "timeout", str(exc)


    except socket.error as exc:
        return "error", str(exc)




def run_noisy(store: ResultStore, args: argparse.Namespace) -> None:
    """Generate controlled payload-free TCP connections (--noisy) for SOC/Sysmon Event ID 3 testing."""
    targets = args.noisy_targets if args.noisy_targets else [args.dc_ip]
    ports = args.noisy_ports if args.noisy_ports else list(DEFAULT_NOISY_PORTS)
    attempts = max(1, args.noisy_count)


    tasks: List[Tuple[str, int, int]] = []


    for target in targets:
        for port in ports:
            for attempt in range(1, attempts + 1):
                tasks.append((target, port, attempt))


    if not tasks:
        return


    def worker(target: str, port: int, attempt: int) -> None:
        """Execute a single controlled TCP probe and record the event."""
        timeout = adaptive_timeout(args.noisy_timeout, attempt % 3, maximum=20.0)
        status, detail = _tcp_probe(target, port, timeout)


        event = NoisyEvent(
            timestamp=utc_now_iso(),
            destination=target,
            port=port,
            protocol="tcp",
            status=status,
            attempt=attempt,
            timeout=round(timeout, 3),
            detail=detail,
            note=(
                "Controlled TCP connect; no payload sent. "
                "Intended for SOC detection testing."
            ),
        )


        store.add_event(event)


        time.sleep(random.uniform(0.15, 0.75))


    max_workers = max(1, min(args.noisy_threads, len(tasks)))


    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        futures = {
            executor.submit(worker, target, port, attempt): (
                target,
                port,
                attempt,
            )
            for target, port, attempt in tasks
        }


        for future in as_completed(futures):
            target, port, attempt = futures[future]
            try:
                future.result()
            except Exception as exc:
                store.add_error(
                    ErrorRecord(
                        timestamp=utc_now_iso(),
                        stage="noisy",
                        message=(
                            f"Noisy probe failed: target={target}, "
                            f"port={port}, attempt={attempt}, error={exc}"
                        ),
                    )
                )




