def utc_now_iso() -> str:
    """Return current UTC timestamp in ISO 8601 format."""
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds")




def adaptive_timeout(base_timeout: float, attempt: int, maximum: float = 30.0) -> float:
    """Calculate adaptive timeout with jitter for unstable VPN tunnels."""
    value = base_timeout * (1.7 ** max(0, attempt))
    value += random.uniform(0.0, 0.35)
    return min(maximum, max(0.5, value))




def backoff_delay(base_timeout: float, attempt: int, maximum: float = 15.0) -> float:
    """Calculate exponential backoff delay with jitter between retries."""
    value = base_timeout * (2 ** max(0, attempt))
    value += random.uniform(0.0, 0.75)
    return min(maximum, value)




def safe_int(value: Any, default: int = 0) -> int:
    """Safely cast a value to int with a fallback default."""
    try:
        return int(str(value).strip())
    except (TypeError, ValueError, AttributeError):
        return default




def as_list(value: Any) -> List[str]:
    """Normalize an LDAP attribute value to a list of strings for JSON export."""
    if value is None:
        return []
    if isinstance(value, (list, tuple, set)):
        return [str(item) for item in value]
    return [str(value)]




def parse_uac(value: int) -> List[str]:
    """Parse numeric userAccountControl bitmask into human-readable flag names."""
    return [name for mask, name in UAC_FLAGS.items() if value & mask]




def domain_to_base_dn(domain: str) -> str:
    """Convert a DNS domain name into an LDAP Base DN."""
    parts = [part.strip() for part in domain.strip().split(".") if part.strip()]
    return ",".join(f"DC={part}" for part in parts)




