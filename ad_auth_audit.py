def main() -> None:
    """Main entry point for the defensive AD authentication audit."""
    args = parse_args()


    store = ResultStore()


    socket.setdefaulttimeout(min(max(args.timeout, 1.0), 30.0))


    if args.noisy:
        run_noisy(store, args)


    auditor = SafeLdapAuditor(
        dc_ip=args.dc_ip,
        domain=args.domain,
        username=args.username,
        password=args.password,
        base_dn=args.base_dn,
        ldap_port=args.ldap_port,
        use_ssl=args.use_ssl,
        insecure_tls=args.insecure_tls,
        attempts=args.attempts,
        base_timeout=args.timeout,
        page_size=args.page_size,
    )


    checks = [
        run_asrep_audit,
        run_spn_audit,
    ]


    max_workers = max(1, min(args.threads, len(checks)))


    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        futures = {
            executor.submit(check, auditor, store, args): check.__name__
            for check in checks
        }


        for future in as_completed(futures):
            check_name = futures[future]
            try:
                future.result()
            except Exception as exc:
                store.add_error(
                    ErrorRecord(
                        timestamp=utc_now_iso(),
                        stage=check_name,
                        message=str(exc),
                    )
                )


    if args.json != "-":
        render_output(store, args)


    if args.json:
        write_json(store, args)


    snapshot = store.snapshot()
    sys.exit(0 if not snapshot["errors"] else 1)




if __name__ == "__main__":
    main()
