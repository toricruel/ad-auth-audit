def run_asrep_audit(
    auditor: SafeLdapAuditor,
    store: ResultStore,
    args: argparse.Namespace,
) -> None:
    """Audit user accounts with DONT_REQUIRE_PREAUTH enabled (read-only AS-REP risk indicator)."""
    entries = auditor.search("asrep_configuration", ASREP_FILTER, ASREP_ATTRIBUTES)


    for entry in entries:
        attrs = entry["attributes"]
        uac = safe_int(attrs.get("userAccountControl"))


        evidence = {
            "sAMAccountName": attrs.get("sAMAccountName"),
            "distinguishedName": entry["dn"],
            "userAccountControl": uac,
            "uacFlags": parse_uac(uac),
            "adminCount": safe_int(attrs.get("adminCount")),
            "memberOf": as_list(attrs.get("memberOf")),
            "pwdLastSet": attrs.get("pwdLastSet"),
            "lastLogonTimestamp": attrs.get("lastLogonTimestamp"),
            "whenCreated": attrs.get("whenCreated"),
            "description": attrs.get("description"),
        }


        finding = Finding(
            timestamp=utc_now_iso(),
            check_id="AS_REP_NO_PREAUTH",
            severity="High",
            object_name=str(attrs.get("sAMAccountName", "")),
            dn=entry["dn"],
            summary=(
                "Account has the DONT_REQUIRE_PREAUTH flag enabled. "
                "Configuration risk associated with AS-REP Roasting. "
                "No Kerberos ticket requests were performed."
            ),
            evidence=evidence,
        )


        store.add_finding(finding)




def run_spn_audit(
    auditor: SafeLdapAuditor,
    store: ResultStore,
    args: argparse.Namespace,
) -> None:
    """Audit user accounts with registered servicePrincipalName (read-only Kerberoasting risk indicator)."""
    entries = auditor.search("spn_configuration", SPN_FILTER, SPN_ATTRIBUTES)


    for entry in entries:
        attrs = entry["attributes"]
        uac = safe_int(attrs.get("userAccountControl"))
        admin_count = safe_int(attrs.get("adminCount"))
        spns = as_list(attrs.get("servicePrincipalName"))


        weak_crypto = bool(uac & 0x00200000)  # USE_DES_KEY_ONLY
        privileged_hint = admin_count > 0


        if privileged_hint or weak_crypto:
            severity = "High"
        else:
            severity = "Medium"


        evidence = {
            "sAMAccountName": attrs.get("sAMAccountName"),
            "distinguishedName": entry["dn"],
            "servicePrincipalName": spns,
            "userAccountControl": uac,
            "uacFlags": parse_uac(uac),
            "adminCount": admin_count,
            "memberOf": as_list(attrs.get("memberOf")),
            "pwdLastSet": attrs.get("pwdLastSet"),
            "lastLogonTimestamp": attrs.get("lastLogonTimestamp"),
            "whenCreated": attrs.get("whenCreated"),
            "msDS-SupportedEncryptionTypes": attrs.get(
                "msDS-SupportedEncryptionTypes"
            ),
            "description": attrs.get("description"),
        }


        finding = Finding(
            timestamp=utc_now_iso(),
            check_id="SPN_SERVICE_ACCOUNT",
            severity=severity,
            object_name=str(attrs.get("sAMAccountName", "")),
            dn=entry["dn"],
            summary=(
                "User account has a registered servicePrincipalName (SPN). "
                "Configuration risk associated with Kerberoasting. "
                "No TGS service ticket requests were performed."
            ),
            evidence=evidence,
        )


        store.add_finding(finding)




