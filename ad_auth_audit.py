class ResultStore:
    """Thread-safe result store using RLock for concurrent audit workers."""


    def __init__(self) -> None:
        """Initialize empty result store and reentrant lock."""
        self._lock = threading.RLock()
        self.findings: List[Dict[str, Any]] = []
        self.events: List[Dict[str, Any]] = []
        self.errors: List[Dict[str, Any]] = []
        self.metrics: Dict[str, int] = {}


    def _inc_metric(self, key: str) -> None:
        """Increment internal metric counter under lock."""
        self.metrics[key] = self.metrics.get(key, 0) + 1


    def add_finding(self, finding: Finding) -> None:
        """Store an audit finding."""
        with self._lock:
            self.findings.append(asdict(finding))
            self._inc_metric("findings")


    def add_event(self, event: NoisyEvent) -> None:
        """Store a controlled noisy network event."""
        with self._lock:
            self.events.append(asdict(event))
            self._inc_metric("noisy_events")


    def add_error(self, error: ErrorRecord) -> None:
        """Store an execution error record."""
        with self._lock:
            self.errors.append(asdict(error))
            self._inc_metric("errors")


    def snapshot(self) -> Dict[str, Any]:
        """Return a thread-safe snapshot of results and metrics for serialization."""
        with self._lock:
            return {
                "findings": self.findings[:],
                "events": self.events[:],
                "errors": self.errors[:],
                "metrics": self.metrics.copy(),
            }




